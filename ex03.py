#Objetivo:Ler três notas digitadas e mostra a média aritmética.

#Entrada:Le os tres numeros digitados. 
nota1 = float(input("Digite a primeira nota:"))
nota2 = float(input("Digite a segunda nota:"))
nota3 = float(input("Digite a terceira nota:"))

#Processamento:Faz o calcula da média das três notas digitadas.
media = (nota1 + nota2 + nota3) /3

#Saída:Mostra a media das tres notas.
print("Media" ,media)
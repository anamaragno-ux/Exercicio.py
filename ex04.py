#Objetivo:Ler a temperatura em Celsis e mostra o vaor em Fahrenheit.

#Entrada:
celsius = float(input(" Digite a temperatura em Celsius:"))

#Processamento:
fahrenheit = celsius * 1.8 + 32 

#Saída:
print("A temperatura em Fahrenheit é:", fahrenheit)
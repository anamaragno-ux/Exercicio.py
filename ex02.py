#Objetivo: Ler dois numeros digitados e mostrar o resultado das operações de soma, subtração, multiplicação e divisão.

#Entrada:Le dois numeros que foi digitado.
numero1 = int(input("Digite o primeiro número:"))
numero2 = int(input("Digite o segundo número:"))

#Processamento:Faz a soma,subtracao e multiplicacao dos numeros digitados.
soma = numero1 + numero2
subtracao = numero1 - numero2
multiplicacao = numero1 * numero2

#Saída: 
print("Soma", soma)
print("Subtracao", subtracao)
print("Multiplicacao", multiplicacao)
